import { pgTable, bigint, uuid, text, timestamp, uniqueIndex, index } from 'drizzle-orm/pg-core'
import { sql } from 'drizzle-orm'
import { relations } from 'drizzle-orm'
import { createInsertSchema, createSelectSchema } from 'drizzle-zod'
import { z } from 'zod'
import { reviewRequests } from './review-requests'
import { users } from '../auth/users'

/**
 * Reviewer inline annotations on a preview surface (spec 04 S-2.21 →
 * _Learner Preview_, reviewer annotation mode, decision D6).
 *
 * A reviewer in preview mode can click any rendered element and leave a
 * comment attached to that element via a CSS selector (the spec calls this
 * "annotation mode"). The annotation is attached to the review request, not
 * the lesson, so it survives a course re-publish and is visible in the
 * review queue.
 *
 * `selector` is a stable CSS selector (e.g. `[data-lesson-id="42"] p:nth-child(3)`)
 * generated by the preview frame's annotation layer. `body` is the
 * reviewer's comment, authored in plain text (no Markdown) to keep the
 * annotation composer lightweight.
 *
 * `resolvedAt` flips when the author addresses the annotation or the review
 * request itself is decided (approved/rejected/withdrawn).
 */
export const reviewAnnotations = pgTable(
  'review_annotations',
  {
    id: bigint('id', { mode: 'number' }).primaryKey().generatedAlwaysAsIdentity(),
    publicId: uuid('public_id').notNull().defaultRandom().unique(),
    reviewRequestId: bigint('review_request_id', { mode: 'number' })
      .notNull()
      .references(() => reviewRequests.id, {
        onDelete: 'cascade',
        onUpdate: 'cascade',
      }),
    /**
     * Stable CSS selector pointing at the annotated element in the preview
     * frame. Generated by the annotation layer, never hand-edited.
     */
    selector: text('selector').notNull(),
    body: text('body').notNull(),
    authorId: text('author_id')
      .notNull()
      .references(() => users.id, {
        onDelete: 'restrict',
        onUpdate: 'cascade',
      }),
    resolvedAt: timestamp('resolved_at', { withTimezone: true }),
    resolvedBy: text('resolved_by').references(() => users.id, {
      onDelete: 'set null',
      onUpdate: 'cascade',
    }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true })
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [
    uniqueIndex('idx_review_annotations_public').on(table.publicId),
    index('idx_review_annotations_request').on(table.reviewRequestId),
    index('idx_review_annotations_author').on(table.authorId),
    index('idx_review_annotations_open')
      .on(table.reviewRequestId)
      .where(sql`${table.resolvedAt} IS NULL`),
  ],
)

export const reviewAnnotationsRelations = relations(reviewAnnotations, ({ one }) => ({
  reviewRequest: one(reviewRequests, {
    fields: [reviewAnnotations.reviewRequestId],
    references: [reviewRequests.id],
  }),
  author: one(users, {
    fields: [reviewAnnotations.authorId],
    references: [users.id],
    relationName: 'review_annotation_author',
  }),
  resolver: one(users, {
    fields: [reviewAnnotations.resolvedBy],
    references: [users.id],
    relationName: 'review_annotation_resolver',
  }),
}))

export const insertReviewAnnotationSchema = createInsertSchema(reviewAnnotations, {
  reviewRequestId: z.number().positive(),
  selector: z.string().min(1),
  body: z.string().min(1).max(2000),
  authorId: z.string().min(1),
  resolvedBy: z.string().nullable().optional(),
}).omit({
  publicId: true,
})
export const selectReviewAnnotationSchema = createSelectSchema(reviewAnnotations)
export const updateReviewAnnotationSchema = insertReviewAnnotationSchema.partial()
export type InsertReviewAnnotation = z.infer<typeof insertReviewAnnotationSchema>
export type SelectReviewAnnotation = z.infer<typeof selectReviewAnnotationSchema>
export type UpdateReviewAnnotation = z.infer<typeof updateReviewAnnotationSchema>
